import assert from "node:assert/strict";
import test from "node:test";
import { randomUUID } from "node:crypto";
import { eq, inArray, like, or } from "drizzle-orm";
import { reportEditSchema, reportSchema, reviewSchema } from "@valrify/validation";
import { AdminService } from "../src/admin/admin.service";
import { ReportsService } from "../src/reports/reports.service";
import { PublicService } from "../src/public/public.service";
import { DatabaseService } from "../src/database/database.service";
import { entities, identifiers, moderationActions, reportEvidence, reportIdentifiers, reportParties, reports, users } from "../src/database/schema";
import type { EvidenceStorage } from "../src/storage/evidence-storage";

test("admin correction keeps separate profiles linked by one case, audited and private until publish", { timeout: 30_000 }, async () => {
  const database = new DatabaseService();
  const target = new URL(process.env.DATABASE_URL ?? "postgresql://localhost:5434/valrify");
  assert(["localhost", "127.0.0.1"].includes(target.hostname) && !target.pathname.includes("prod"), "Integration test requires a local non-production database");
  const suffix = randomUUID();
  const reporterId = `edit-user-${suffix}`, adminId = `edit-admin-${suffix}`;
  const referrerName = `Referrer ${suffix}`, middlemanName = `Middleman ${suffix}`;
  const phone = `08991${Date.now()}`;
  const bytes = Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]);
  const file = { originalname: "fixture.png", mimetype: "image/png", buffer: bytes, size: bytes.length } as Express.Multer.File;
  const storage = { get: async () => bytes, put: async (_file: Express.Multer.File, reportId: number) => ({ key: `fixture-${reportId}`, fileName: "fixture.png", mimeType: "image/png", size: bytes.length }) } as EvidenceStorage;
  const admin = new AdminService(database, storage), service = new ReportsService(database, storage), publicService = new PublicService(database, storage);
  const reportIds: number[] = [];
  try {
    await database.db.insert(users).values([{ id: reporterId, email: `${reporterId}@valrify.local`, displayName: "Fixture reporter", emailVerifiedAt: new Date() }, { id: adminId, email: `${adminId}@valrify.local`, displayName: "Fixture admin", role: "ADMIN", emailVerifiedAt: new Date() }]);
    const originalChronology = "Laporan awal mengenai akun pengarah sebelum identitas rekber tambahan diperiksa.";
    const created = await service.create(reporterId, reportSchema.parse({ entityName: referrerName, chronology: originalChronology, category: "OTHER", identifiers: [{ type: "FACEBOOK_NAME", value: referrerName }] }), [file]);
    reportIds.push(created.id);
    const original = (await database.db.query.reports.findFirst({ where: eq(reports.id, created.id) }))!;
    const input = reportEditSchema.parse({ updatedAt: original.updatedAt.toISOString(), chronology: "Pengarah menyarankan akun rekber lain yang kemudian meminta deposit tambahan dalam transaksi.", category: "FAKE_MIDDLEMAN", transactionDate: "2026-10-28", evidenceUrl: "", rationale: "Menambahkan pihak rekber terpisah sesuai screenshot bukti.", parties: [{ entityId: original.entityId, entityName: referrerName, role: "REFERRER", identifiers: [{ type: "FACEBOOK_NAME", value: referrerName }] }, { entityName: middlemanName, role: "MIDDLEMAN", identifiers: [{ type: "FACEBOOK_NAME", value: middlemanName }, { type: "PHONE", value: phone }, { type: "BANK_ACCOUNT", value: phone, provider: "BCA" }] }] });
    await assert.rejects(admin.editReport(created.id, reporterId, input), /sendiri/);
    await admin.editReport(created.id, adminId, input);
    await assert.rejects(admin.editReport(created.id, adminId, input), /berubah/);
    const parties = await database.db.select().from(reportParties).where(eq(reportParties.reportId, created.id)).orderBy(reportParties.position);
    assert.equal(parties.length, 2);
    assert.notEqual(parties[0]!.entityId, parties[1]!.entityId);
    const audit = await database.db.query.moderationActions.findFirst({ where: eq(moderationActions.reportId, created.id) });
    assert.equal(audit?.action, "REPORT_EDITED");
    assert.equal((audit?.details as { before: { report: { chronology: string } } }).before.report.chronology, originalChronology);
    assert.deepEqual(await publicService.search(phone), []);
    assert.equal(await publicService.publicCase(created.publicId), null);
    const pending = (await admin.queue()).find(row => row.id === created.id)!;
    assert.equal(pending.parties.length, 2);
    assert.equal(pending.parties[1]!.role, "MIDDLEMAN");
    assert.equal(pending.parties[0]!.identifiers.some(id => id.value === phone), false);
    assert.equal(pending.parties[1]!.identifiers.some(id => id.value === phone), true);
    // Concurrent saves use the same version: one commits and the other must reload.
    const current = (await database.db.query.reports.findFirst({ where: eq(reports.id, created.id) }))!;
    const concurrentInput = { ...input, updatedAt: current.updatedAt.toISOString(), parties: pending.parties.map(party => ({ ...party, identifiers: party.identifiers.map(id => id.type === "BANK_ACCOUNT" ? { ...id, provider: "SeaBank" } : id) })) as typeof input.parties };
    const concurrent = await Promise.allSettled([admin.editReport(created.id, adminId, concurrentInput), admin.editReport(created.id, adminId, concurrentInput)]);
    assert.equal(concurrent.filter(result => result.status === "fulfilled").length, 1);
    const corrected = (await admin.queue()).find(row => row.id === created.id)!;
    assert.equal(corrected.parties[1]!.identifiers.find(id => id.type === "BANK_ACCOUNT")!.provider, "SeaBank");
    const evidence = await database.db.query.reportEvidence.findFirst({ where: eq(reportEvidence.reportId, created.id) });
    const publish = reviewSchema.parse({ decision: "PUBLISH", summary: "Ringkasan netral yang menjelaskan pengarah dan rekber sebagai dua akun yang berbeda.", rationale: "Bukti mendukung data masing-masing pihak dalam kasus ini.", publicEvidenceIds: [evidence!.id] });
    await assert.rejects(admin.review(created.id, adminId, { ...publish, updatedAt: original.updatedAt.toISOString() }), /diubah/);
    await admin.review(created.id, adminId, publish);
    await assert.rejects(admin.editReport(created.id, adminId, concurrentInput), /berubah/);
    const publishedRow = (await database.db.query.reports.findFirst({ where: eq(reports.id, created.id) }))!;
    const publicSummary = "Ringkasan publik dikoreksi sesuai bukti terbaru tanpa menarik laporan dari publik.";
    const publishedEdit = { ...concurrentInput, updatedAt: publishedRow.updatedAt.toISOString(), publicSummary };
    await database.db.update(users).set({ role: "VERIFIED_MIDDLEMAN" }).where(eq(users.id, reporterId));
    await assert.rejects(admin.editReport(created.id, reporterId, publishedEdit), /hanya dapat dilakukan/);
    await admin.editReport(created.id, adminId, publishedEdit);
    assert.equal((await publicService.publicCase(created.publicId))!.publicSummary, publicSummary);
    const afterEdit = (await database.db.query.reports.findFirst({ where: eq(reports.id, created.id) }))!;
    assert.equal(afterEdit.status, "PUBLISHED");
    assert.equal(afterEdit.publishedAt!.getTime(), publishedRow.publishedAt!.getTime());
    await database.db.update(reportEvidence).set({ isPublicApproved: false }).where(eq(reportEvidence.reportId, created.id));
    await assert.rejects(admin.editReport(created.id, adminId, { ...publishedEdit, updatedAt: afterEdit.updatedAt.toISOString() }), /harus tetap memiliki/);
    await database.db.update(reportEvidence).set({ isPublicApproved: true }).where(eq(reportEvidence.reportId, created.id));
    const search = await publicService.search(phone);
    assert.equal(search.length, 1);
    assert.equal(search[0]!.entityId, parties[1]!.entityId);
    assert.equal(search[0]!.reportCount, 1);
    const profile = await publicService.entity(search[0]!.slug);
    assert.equal(profile!.reports[0]!.publicId, created.publicId);
    assert.equal(profile!.aliases.some(id => id.displayValue === referrerName), false);
    const primarySearch = await publicService.search(referrerName);
    assert.equal(primarySearch.length, 1);
    assert.notEqual(primarySearch[0]!.entityId, search[0]!.entityId);
    const primaryProfile = await publicService.entity(primarySearch[0]!.slug);
    assert.equal(primaryProfile!.identifiers.some(id => id.displayValue === phone), false);
    const publicCase = await publicService.publicCase(created.publicId);
    assert.equal(publicCase!.parties.length, 2);
    assert.equal(publicCase!.parties[0]!.identifiers.some(id => id.displayValue === phone), false);
    assert.equal(publicCase!.parties[1]!.identifiers.some(id => id.displayValue === phone), true);
    assert.equal(JSON.stringify(publicCase).includes(originalChronology), false);
    // A later report can match the published middleman's phone without renaming that profile.
    const followup = await service.create(reporterId, reportSchema.parse({ entityName: `Alias ${suffix}`, chronology: originalChronology, category: "OTHER", identifiers: [{ type: "PHONE", value: phone }] }), [file]);
    reportIds.push(followup.id);
    assert.equal(followup.linkedToExistingProfile, true);
    const reused = (await database.db.query.entities.findFirst({ where: eq(entities.id, parties[1]!.entityId) }))!;
    assert.equal(reused.displayName, middlemanName);
    const otherBank = await service.create(reporterId, reportSchema.parse({ entityName: `Other bank ${suffix}`, chronology: originalChronology, category: "OTHER", identifiers: [{ type: "BANK_ACCOUNT", value: phone, provider: "BCA" }] }), [file]);
    reportIds.push(otherBank.id);
    assert.equal(otherBank.linkedToExistingProfile, false);
    assert.notEqual((await database.db.query.reports.findFirst({ where: eq(reports.id, otherBank.id) }))!.entityId, reused.id);
    const followupRow = (await database.db.query.reports.findFirst({ where: eq(reports.id, followup.id) }))!;
    await admin.editReport(followup.id, adminId, { ...input, updatedAt: followupRow.updatedAt.toISOString(), parties: [{ entityId: reused.id, entityName: `Corrected ${suffix}`, role: "REPORTED", identifiers: [{ type: "PHONE", value: phone }] }] });
    assert.equal((await database.db.query.entities.findFirst({ where: eq(entities.id, reused.id) }))!.displayName, middlemanName);
    assert.deepEqual(await publicService.search(`Corrected ${suffix}`), []);
    await admin.review(created.id, adminId, reviewSchema.parse({ decision: "WITHDRAW", rationale: "Penarikan fixture untuk memeriksa privasi seluruh pihak." }));
    assert.deepEqual(await publicService.search(phone), []);
    assert.deepEqual(await publicService.search(referrerName), []);
    assert.equal(await publicService.publicCase(created.publicId), null);
    assert.equal(await publicService.publicEvidence(created.publicId, evidence!.id), null);
    const dual = await service.create(reporterId, reportSchema.parse({ entityName: `Two banks ${suffix}`, chronology: originalChronology, category: "OTHER", identifiers: [{ type: "BANK_ACCOUNT", value: `${phone}9`, provider: "BCA" }, { type: "BANK_ACCOUNT", value: `${phone}9`, provider: "SeaBank" }] }), [file]);
    reportIds.push(dual.id);
    const dualIdentifiers = await database.db.select({ type: identifiers.type }).from(reportIdentifiers).innerJoin(identifiers, eq(identifiers.id, reportIdentifiers.identifierId)).where(eq(reportIdentifiers.reportId, dual.id));
    assert.equal(dualIdentifiers.filter(id => id.type === "BANK_ACCOUNT").length, 2);
  } finally {
    if (reportIds.length) {
      await database.db.delete(moderationActions).where(inArray(moderationActions.reportId, reportIds));
      await database.db.delete(reports).where(inArray(reports.id, reportIds));
    }
    await database.db.delete(entities).where(like(entities.displayName, `%${suffix}%`));
    await database.db.delete(identifiers).where(or(like(identifiers.rawValue, `%${suffix}%`), eq(identifiers.rawValue, phone), eq(identifiers.rawValue, `${phone}9`)));
    await database.db.delete(users).where(inArray(users.id, [reporterId, adminId]));
    await database.onModuleDestroy();
  }
});
